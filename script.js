const grid = document.querySelector("#guide-grid");
const searchInput = document.querySelector("#guide-search");
const searchForm = document.querySelector("#search-form");
const resultsMeta = document.querySelector("#results-meta");
const emptyState = document.querySelector("#empty-state");
const savedToggle = document.querySelector("#saved-toggle");
const savedCount = document.querySelector("#saved-count");
const dialog = document.querySelector("#guide-dialog");
const dialogContent = document.querySelector("#dialog-content");
const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector("#main-nav");

let activeCategory = "Tout";
let savedOnly = false;
let savedGuides = loadSavedGuides();

function loadSavedGuides() {
  try {
    const saved = JSON.parse(localStorage.getItem("declic-favorites") || "[]");
    return new Set(Array.isArray(saved) ? saved.filter((id) => guides.some((guide) => guide.id === id)) : []);
  } catch (error) {
    console.warn("Impossible de charger les favoris enregistrés.", error);
    return new Set();
  }
}

function persistSavedGuides() {
  try {
    localStorage.setItem("declic-favorites", JSON.stringify([...savedGuides]));
  } catch (error) {
    console.error("Impossible d’enregistrer les favoris dans ce navigateur.", error);
    resultsMeta.textContent = "Vos favoris ne peuvent pas être enregistrés dans ce navigateur.";
  }
}

function normalizeText(value) {
  return value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLocaleLowerCase("fr");
}

function iconForBookmark() {
  return `<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 4.75A1.75 1.75 0 0 1 7.75 3h8.5A1.75 1.75 0 0 1 18 4.75V21l-6-4-6 4V4.75Z"/></svg>`;
}

function visibleGuides() {
  const query = normalizeText(searchInput.value.trim());
  return guides.filter((guide) => {
    const matchesCategory = activeCategory === "Tout" || guide.category === activeCategory;
    const matchesQuery = !query || normalizeText(`${guide.title} ${guide.description} ${guide.category} ${guide.keywords}`).includes(query);
    const matchesSaved = !savedOnly || savedGuides.has(guide.id);
    return matchesCategory && matchesQuery && matchesSaved;
  });
}

function renderGuides() {
  const shownGuides = visibleGuides();
  grid.innerHTML = shownGuides.map((guide, index) => `
    <article class="guide-card" style="animation-delay:${Math.min(index * 35, 210)}ms">
      <div class="card-top">
        <span class="category-label" data-category="${guide.category}"><span class="category-dot"></span>${guide.category}</span>
        <button class="bookmark-button" type="button" data-save="${guide.id}" aria-label="${savedGuides.has(guide.id) ? "Retirer des favoris" : "Ajouter aux favoris"} : ${guide.title}" aria-pressed="${savedGuides.has(guide.id)}">${iconForBookmark()}</button>
      </div>
      <button class="card-open" type="button" data-open="${guide.id}" aria-label="Lire le guide : ${guide.title}">
        <span class="card-icon" aria-hidden="true">${guide.icon}</span>
        <span class="card-title">${guide.title}</span>
        <span class="card-description">${guide.description}</span>
      </button>
      <div class="card-footer"><span>⏱ &nbsp;${guide.duration} de lecture</span><span aria-hidden="true">↗</span></div>
    </article>
  `).join("");
  grid.hidden = shownGuides.length === 0;
  emptyState.hidden = shownGuides.length !== 0;
  if (savedOnly) {
    resultsMeta.textContent = `${shownGuides.length} guide${shownGuides.length === 1 ? "" : "s"} dans vos favoris`;
  } else if (searchInput.value.trim()) {
    resultsMeta.textContent = `${shownGuides.length} résultat${shownGuides.length === 1 ? "" : "s"} pour « ${searchInput.value.trim()} »`;
  } else {
    resultsMeta.textContent = "";
  }
  savedCount.textContent = String(savedGuides.size);
  savedToggle.setAttribute("aria-pressed", String(savedOnly));
}

function setCategory(category) {
  activeCategory = category;
  document.querySelectorAll(".filter-chip").forEach((chip) => {
    const selected = chip.dataset.category === category;
    chip.classList.toggle("selected", selected);
    chip.setAttribute("aria-pressed", String(selected));
  });
  renderGuides();
}

function openGuide(id) {
  const guide = guides.find((item) => item.id === id);
  if (!guide) return;
  dialogContent.innerHTML = `
    <span class="dialog-category"><span></span>${guide.category} · ${guide.duration} de lecture</span>
    <h2 id="dialog-title">${guide.title}</h2>
    <p class="dialog-lead">${guide.lead}</p>
    <h3>Les étapes, tout simplement</h3>
    <ol class="dialog-steps">${guide.steps.map((step) => `<li>${step}</li>`).join("")}</ol>
    <p class="dialog-tip"><strong>Le petit rappel :</strong> ${guide.tip}</p>
    <button class="dialog-save" type="button" data-save="${guide.id}" aria-pressed="${savedGuides.has(guide.id)}">${savedGuides.has(guide.id) ? "✓ Dans mes favoris" : "＋ Ajouter à mes favoris"}</button>
  `;
  dialog.showModal();
}


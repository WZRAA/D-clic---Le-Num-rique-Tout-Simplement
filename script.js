grid.addEventListener("click", (event) => {
  const saveButton = event.target.closest("[data-save]");
  if (saveButton) {
    const id = saveButton.dataset.save;
    if (savedGuides.has(id)) savedGuides.delete(id);
    else savedGuides.add(id);
    persistSavedGuides();
    renderGuides();
    if (dialog.open) openGuide(id);
    return;
  }
  const openButton = event.target.closest("[data-open]");
  if (openButton) openGuide(openButton.dataset.open);
});

dialog.addEventListener("click", (event) => {
  if (event.target === dialog || event.target.closest(".dialog-close")) dialog.close();
  const saveButton = event.target.closest("[data-save]");
  if (!saveButton) return;
  const id = saveButton.dataset.save;
  if (savedGuides.has(id)) savedGuides.delete(id);
  else savedGuides.add(id);
  persistSavedGuides();
  renderGuides();
  openGuide(id);
});

